import os
from datetime import datetime
from typing import Dict, Any, List, Optional
import httpx
from app.core.config import settings
from app.services.market_service import MarketService
from app.analytics.technical import compute_all_technical_indicators
from app.analytics.fundamental import compute_health_score

class AssistantService:
    def __init__(self, market_service: MarketService):
        self.market_service = market_service

    def answer_query(
        self,
        message: str,
        symbol: Optional[str] = None,
        conversation_history: Optional[List[Dict[str, str]]] = None
    ) -> Dict[str, Any]:
        """
        Grounded financial conversational agent that answers market, company,
        technical, and prediction questions using verified application data.
        """
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")
        msg_lower = message.lower()
        
        # Detect symbol from query if not explicitly passed
        target_symbol = symbol
        if not target_symbol:
            for s in ["RELIANCE", "TCS", "INFY", "HDFCBANK", "ICICIBANK", "SBIN", "TATAMOTORS", "AAPL", "MSFT", "NVDA", "GOOGL", "AMZN", "TSLA"]:
                if s.lower() in msg_lower:
                    target_symbol = s
                    break

        sources = []
        context_data = ""

        if target_symbol:
            quote = self.market_service.get_stock_quote(target_symbol)
            sources.append(f"Market Quote ({quote.get('provider', 'Demo')}) as of {quote.get('data_timestamp')}")
            
            try:
                hist_df = self.market_service.get_provider().get_historical_ohlcv(target_symbol, timeframe="1Y")
                tech = compute_all_technical_indicators(hist_df, target_symbol)
                sources.append("MarketMind Technical Indicator Engine")
            except Exception:
                tech = None

            try:
                fin = self.market_service.get_financials(target_symbol)
                health = compute_health_score(fin.get("metrics", {}))
                sources.append("Company Fundamentals & Health Scoring Framework")
            except Exception:
                health = None

            context_data = f"""
Symbol: {target_symbol} ({quote.get('name')})
Exchange: {quote.get('exchange')} | Currency: {quote.get('currency')}
Price: {quote.get('price')} ({quote.get('change_pct')}% change)
Day Range: {quote.get('day_low')} - {quote.get('day_high')}
P/E Ratio: {quote.get('pe_ratio')} | Div Yield: {quote.get('dividend_yield')}%
"""
            if tech:
                context_data += f"Technical: RSI(14)={tech['rsi_14']} ({tech['rsi_signal']}), MACD={tech['macd']} ({tech['macd_trend']}), Sentiment={tech['overall_sentiment']}\n"
            if health:
                context_data += f"Health Score: {health['health_score']}/100 ({health['health_rating']})\nKey Strengths: {', '.join(health['strengths'])}\nKey Risks: {', '.join(health['risks'])}\n"

        # Check if Gemini API Key is configured
        if settings.GEMINI_API_KEY:
            try:
                reply = self._call_gemini_api(message, context_data, target_symbol)
                return {
                    "reply": reply,
                    "symbol": target_symbol,
                    "data_timestamp": now_str,
                    "sources_cited": sources,
                    "disclaimer": "Educational analysis generated by AI. Not financial advice."
                }
            except Exception as e:
                # Fall back to rules-based grounded responder
                pass

        # Built-in expert financial reasoning engine
        reply = self._generate_grounded_reply(message, target_symbol, context_data)
        if not sources:
            sources.append("MarketMind Financial Knowledge Base")

        return {
            "reply": reply,
            "symbol": target_symbol,
            "data_timestamp": now_str,
            "sources_cited": sources,
            "disclaimer": "Educational analysis grounded in historical and reported data. MarketMind does not provide personalized investment advice."
        }

    def _generate_grounded_reply(self, message: str, symbol: Optional[str], context_data: str) -> str:
        msg = message.lower()

        if "rsi" in msg:
            return (
                "**Relative Strength Index (RSI)** is a momentum oscillator measuring the speed and velocity of price movements on an index of 0 to 100.\n\n"
                "- **Overbought (>70)**: Suggests buying momentum is mature and the price may be extended.\n"
                "- **Oversold (<30)**: Indicates heavy selling pressure where a technical bounce or stabilization often occurs.\n"
                "- **Divergence**: When price makes a higher high but RSI prints a lower high, it warns of weakening underlying momentum.\n\n"
                f"{context_data if symbol else 'Select any stock in the platform to inspect its real-time 14-day Wilder RSI calculations.'}"
            )

        if "macd" in msg:
            return (
                "**MACD (Moving Average Convergence Divergence)** tracks trend direction and momentum by subtracting the 26-period EMA from the 12-period EMA.\n\n"
                "- **Signal Line (9-EMA)**: Acts as a trigger line. When MACD crosses above it, it represents a bullish crossover.\n"
                "- **Histogram**: Represents the distance between MACD and its signal line. Expanding bars signal accelerating momentum.\n\n"
                f"{context_data if symbol else ''}"
            )

        if symbol:
            if "risk" in msg or "safe" in msg:
                return (
                    f"### Risk Assessment for {symbol}\n\n"
                    f"{context_data}\n"
                    "**Key Risk Factors:**\n"
                    "1. **Valuation Multiples**: Review the P/E and EV/EBITDA ratios relative to sector peers.\n"
                    "2. **Balance Sheet Health**: Examine Debt-to-Equity and interest coverage to assess debt servicing capacity.\n"
                    "3. **Market Volatility**: Check the Risk Analysis tab to evaluate historical Maximum Drawdown and Beta.\n\n"
                    "*Note: Past stability does not guarantee protection against sudden industry or macroeconomic downturns.*"
                )

            if "prediction" in msg or "forecast" in msg or "future" in msg:
                return (
                    f"### Model Forecast Overview for {symbol}\n\n"
                    f"{context_data}\n"
                    "MarketMind evaluates multiple machine learning architectures (Random Forest, Gradient Boosting, Ridge Baseline) "
                    "calibrated strictly on chronological historical price/volume time-series.\n\n"
                    "**Crucial Methodology Notes:**\n"
                    "- Every horizon (1D, 5D, 7D, 30D, 90D) features an empirical 80% prediction interval reflecting statistical uncertainty.\n"
                    "- Longer horizons (e.g. 90-day) carry significantly wider uncertainty bands due to non-stationarity.\n"
                    "- Check the **AI Prediction Centre** tab to view out-of-sample MAE, RMSE, and walk-forward directional accuracy."
                )

            return (
                f"### Analysis Overview for {symbol}\n\n"
                f"{context_data}\n"
                "You can explore deeper insights for this stock across the platform:\n"
                "- **Technical Analysis**: Interactive RSI, MACD, and Bollinger Bands with detected candlestick patterns.\n"
                "- **Fundamental Research**: Health Score breakdown, debt analysis, and quarterly earnings trends.\n"
                "- **AI Prediction Centre**: Machine learning forecasts with baseline comparison and uncertainty bands.\n"
                "- **Risk Analysis**: Value at Risk (VaR 95%), Beta, and Sharpe ratio.\n\n"
                "What specific aspect would you like me to analyze further?"
            )

        return (
            "Hello! I am **MarketMind AI Assistant**, your financial analytics companion.\n\n"
            "I can assist you with:\n"
            "- **Company Deep-Dives**: Asking about specific Indian (e.g. RELIANCE, TCS, INFY) or US (e.g. AAPL, NVDA, MSFT) stocks.\n"
            "- **Technical Explanations**: Deciphering RSI, MACD, Moving Averages, and Chart Patterns.\n"
            "- **Risk & Health Scores**: Explaining our transparent 4-pillar financial health scoring system.\n"
            "- **Machine Learning Forecasts**: Breaking down walk-forward validation and prediction intervals.\n\n"
            "Try asking: *'How healthy is TCS's balance sheet?'* or *'Explain NVDA's technical indicators'*."
        )

    def _call_gemini_api(self, query: str, context: str, symbol: Optional[str]) -> str:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={settings.GEMINI_API_KEY}"
        system_prompt = (
            "You are MarketMind Financial Assistant, a knowledgeable, objective financial technology analyst. "
            "Use only the provided facts and data. Explicitly cite data sources and timestamps. "
            "Never guarantee investment returns or future prices. Clarify uncertainty and risk."
        )
        payload = {
            "contents": [{
                "parts": [
                    {"text": f"{system_prompt}\n\nContext Data:\n{context}\n\nUser Question: {query}"}
                ]
            }],
            "generationConfig": {
                "temperature": 0.2,
                "maxOutputTokens": 600
            }
        }
        with httpx.Client(timeout=10.0) as client:
            resp = client.post(url, json=payload)
            resp.raise_for_status()
            res_json = resp.json()
            return res_json["candidates"][0]["content"]["parts"][0]["text"]
